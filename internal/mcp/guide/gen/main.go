// Command gen writes the MCP guide resources from the ACR registries into
// ../zz_generated.go. Run it with go generate ./internal/mcp/guide.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"sort"

	"github.com/full-chaos/dev-health-acr/internal/mcp/guide/guidegen"
)

func main() {
	files, err := guidegen.Build(guidegen.FromRegistries())
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	names := make([]string, 0, len(files))
	for name := range files {
		names = append(names, name)
	}
	sort.Strings(names)
	var buf bytes.Buffer
	buf.WriteString("// Code generated by internal/mcp/guide/gen from the ACR registries. DO NOT EDIT.\n\n")
	buf.WriteString("package guide\n\n")
	buf.WriteString("// generated holds the guide text by file name. It is Go source, not an\n")
	buf.WriteString("// embedded file, so the container build context needs no extra allowlist entry.\n")
	buf.WriteString("var generated = map[string]string{\n")
	for _, name := range names {
		fmt.Fprintf(&buf, "\t%q: %q,\n", name, files[name])
	}
	buf.WriteString("}\n")
	out, err := format.Source(buf.Bytes())
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	// go:generate runs with cwd == the directory holding the directive.
	if err := os.WriteFile("zz_generated.go", out, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
