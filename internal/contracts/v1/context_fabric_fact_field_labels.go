//
// Each row is a plain noun phrase, so it reads as a table heading and as the
// name of a single value. It keeps the words of the declaration. It claims no
// more than the field does: a p50 reads "Median", a p90 "90th percentile", and a
// name this table cannot expand stays as it is (MTTR), because a wrong metric
// word is worse than a raw one.
//
// The unit stands in the label, because the consumer has no other place to read
// it: the unit word of the declaration, or " (unit)" at the end. A count has no
// word (the noun is its unit), and an axis reads "coordinate".
//
// Totality runs both ways over the real declarations in
// devhealthfacts/chaos12418_fact_field_labels_test.go: a new declaration cannot
