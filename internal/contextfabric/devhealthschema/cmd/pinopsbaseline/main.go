// Command pinopsbaseline regenerates testdata/ops_baseline_pinned_tables.sql
// from ops internal/chmigrate/baseline/head.json, and with -go prints the
// ProductionColumns and EngineFull entries for the pinned tables.
//
//	go run ./internal/contextfabric/devhealthschema/cmd/pinopsbaseline \
//	  -head <ops>/internal/chmigrate/baseline/head.json -ops-commit <sha> \
//	  -out internal/contextfabric/devhealthschema/testdata/ops_baseline_pinned_tables.sql
package main

import (
	"crypto/sha256"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"strings"

	"github.com/full-chaos/dev-health-acr/internal/contextfabric/devhealthschema"
)

var pinned = []string{
	"ai_workflow_artifact_edges",
	"ai_workflow_runs",
	"git_commit_stats",
	"git_commits",
	"work_graph_edges",
	"work_graph_pr_review_outcome_edges",
}

func main() {
	head := flag.String("head", "", "path to ops baseline/head.json")
	commit := flag.String("ops-commit", "", "ops commit the head.json was read at")
	out := flag.String("out", "", "testdata file to write")
	emitGo := flag.Bool("go", false, "print schema.go entries instead of writing -out")
	flag.Parse()
	if *head == "" || *commit == "" || (*out == "" && !*emitGo) {
		fmt.Fprintln(os.Stderr, "usage: -head FILE -ops-commit SHA (-out FILE | -go)")
		os.Exit(2)
	}
	raw, err := os.ReadFile(*head)
	check(err)
	var baseline struct {
		Objects []struct{ Name, Create string } `json:"objects"`
	}
	check(json.Unmarshal(raw, &baseline))
	creates := map[string]string{}
	for _, o := range baseline.Objects {
		creates[o.Name] = o.Create
	}
	if *emitGo {
		var cols, engines strings.Builder
		for _, name := range pinned {
			parsed, err := devhealthschema.ParseOpsCreate(creates[name])
			check(err)
			fmt.Fprintf(&cols, "\t%q: {\n", name)
			for _, c := range parsed.Columns {
				fmt.Fprintf(&cols, "\t\t{Name: %q, Type: %q},\n", c.Name, c.Type)
			}
			cols.WriteString("\t},\n")
			fmt.Fprintf(&engines, "\t%q: %q,\n", name, parsed.Engine)
		}
		fmt.Print("// ProductionColumns\n", cols.String(), "// EngineFull\n", engines.String())
		return
	}
	var b strings.Builder
	fmt.Fprintf(&b, "-- Generated by cmd/pinopsbaseline; do not edit.\n-- ops commit: %s\n-- baseline/head.json sha256: %x\n", *commit, sha256.Sum256(raw))
	for _, name := range pinned {
		stmt, ok := creates[name]
		if !ok {
			check(fmt.Errorf("baseline has no object %q", name))
		}
		fmt.Fprintf(&b, "\n%s\n", stmt)
	}
	check(os.WriteFile(*out, []byte(b.String()), 0o644))
}

func check(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
