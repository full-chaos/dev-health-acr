// traceFrame is one frame of the executed trace.
type traceFrame struct {
	// id is the question ID. NEVER the question text.
	id string
	// shape is a STRUCTURAL label -- topology plus operation -- not a
	// paraphrase: it names the frame, not the question.
	shape string
	frame contextfabric.QuestionFrame
	// recorded marks the thirteen frames of the trace ON RECORD. C2s is
	// the one addition (see traceExplicitMixed) and is false, so the
	// artifact can report a subtotal that stays comparable to the
	// measurement of record.
	recorded bool
}

func traceKindPointer(kind contextfabric.SubjectKind) *contextfabric.SubjectKind {
	return &kind
}

func traceBuildFrame(
	goals []contextfabric.InvestigationGoal,
	expression contextfabric.SubjectExpression,
	temporal contextfabric.TemporalIntent,
	emphasis []contextfabric.AnswerEmphasis,
	dimensions []contextfabric.HealthDimension,
) contextfabric.QuestionFrame {
	return contextfabric.DeriveFrameObligations(contextfabric.QuestionFrame{
		Goals:             goals,
		SubjectExpression: expression,
		Temporal:          temporal,
		Emphasis:          emphasis,
		Dimensions:        dimensions,
		Version:           contextfabric.QuestionFrameVersion,
	}, nil)
}

func traceNamed(kind contextfabric.SubjectKind) contextfabric.SubjectExpression {
	return contextfabric.SubjectExpression{
		Kind:  contextfabric.SubjectExpressionNamed,
		Named: &contextfabric.NamedSubjectExpression{Terms: []string{"s"}, ExpectedKind: traceKindPointer(kind)},
	}
}

func traceDiscovered(member contextfabric.SubjectKind) contextfabric.SubjectExpression {
	return contextfabric.SubjectExpression{
		Kind:       contextfabric.SubjectExpressionDiscoveredKind,
		Discovered: &contextfabric.DiscoveredSetExpression{MemberKind: member},
	}
}

func traceGrouped(group, member contextfabric.SubjectKind) contextfabric.SubjectExpression {
	return contextfabric.SubjectExpression{
		Kind:    contextfabric.SubjectExpressionGroupedMembers,
		Grouped: &contextfabric.GroupedSetExpression{GroupKind: group, MemberKind: member},
	}
}

func traceScoped(member contextfabric.SubjectKind) contextfabric.SubjectExpression {
	return contextfabric.SubjectExpression{
		Kind:   contextfabric.SubjectExpressionChildrenOfScope,
		Scoped: &contextfabric.ScopedSetExpression{AnchorTerms: []string{"a"}, MemberKind: member},
	}
}

// traceExplicit builds the comparison used by C2 and C6, FAITHFUL to the
// recorded corpus: two NAMED operands of the same kind.
//
// It is kept exactly as the recorded trace had it so that this gate's
// measurement stays directly comparable to the one on record. Changing the
// corpus and the derivation in the same change would make any movement in
// the numbers unattributable.
func traceExplicit(kind contextfabric.SubjectKind) contextfabric.SubjectExpression {
	operand := func(term string) contextfabric.SubjectOperand {
		return contextfabric.SubjectOperand{
			Kind:  contextfabric.SubjectOperandNamed,
			Named: &contextfabric.NamedSubjectExpression{Terms: []string{term}, ExpectedKind: traceKindPointer(kind)},
		}
	}
	return contextfabric.SubjectExpression{
		Kind:     contextfabric.SubjectExpressionExplicitSet,
		Explicit: &contextfabric.ExplicitSetExpression{Operands: []contextfabric.SubjectOperand{operand("a"), operand("b")}},
	}
}

// traceExplicitMixed is C2s, the ONE frame ADDED to the recorded corpus,
// and it is added for a reason the record itself supplies.
//
// Every explicit set in the thirteen recorded frames has two NAMED operands.
// SubjectOperand is a union of named AND scoped (invariant I19), and round 3
// of the declaration slice found the coordinate derivation reading the named
// arm only -- a scoped operand's cells vanished and every test stayed green,
// precisely because no frame in the corpus had one. A corpus that cannot
// exhibit a defect cannot gate against it.
//
// It is a SEPARATE frame rather than a change to C2 so that the thirteen
// recorded frames keep their recorded shape: the artifact reports the
// thirteen-frame subtotal alongside the total, so the measurement of record
// stays comparable and this addition is visible rather than folded in.
func traceExplicitMixed() contextfabric.SubjectExpression {
	return contextfabric.SubjectExpression{
		Kind: contextfabric.SubjectExpressionExplicitSet,
		Explicit: &contextfabric.ExplicitSetExpression{Operands: []contextfabric.SubjectOperand{
			{Kind: contextfabric.SubjectOperandNamed, Named: &contextfabric.NamedSubjectExpression{Terms: []string{"a"}, ExpectedKind: traceKindPointer(contextfabric.SubjectTeam)}},
			{Kind: contextfabric.SubjectOperandScoped, Scoped: &contextfabric.ScopedSetExpression{AnchorTerms: []string{"b"}, MemberKind: contextfabric.SubjectProject}},
		}},
	}
}

func traceOrg(member *contextfabric.SubjectKind) contextfabric.SubjectExpression {
	return contextfabric.SubjectExpression{
		Kind: contextfabric.SubjectExpressionOrganizationScope,
		Org:  &contextfabric.OrganizationScopeExpression{MemberKind: member},
	}
}

