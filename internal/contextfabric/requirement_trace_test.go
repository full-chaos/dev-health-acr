// The live registry's declarations come from liveCapabilityList, declared
// in obligation_seed_test.go and REUSED here rather than re-read, so "the
// live registry" has exactly ONE definition in this package's external test
// binary. Two readers of the same registry that could disagree is the shape
// of defect this slice's whole review history is about. It reads
// Capability() declarations only and constructs no provider client, so
// nothing in this file touches ClickHouse or starts a container.

// recordedFrameCount is how many of the corpus frames are the trace ON
// RECORD. Derived from the corpus rather than written down, so adding a
// frame cannot leave a stale constant behind.
func recordedFrameCount() int {
	count := 0
	for _, testCase := range traceFrames() {
		if testCase.recorded {
			count++
		}
	}
	return count
}

// TestEveryRequirementCellIsServedOrNamesAClosedReason is oracle O9's own
// assertion: never silently empty.
//
// This is the condition the entry gate was written to reach, and reaching
// it is what replaces the declaration slice's pinned baseline. It does NOT
// say the registry can serve everything -- it says that where it cannot,
// the derivation SAYS SO, with a token from a closed vocabulary that names
// what would have to change.
func TestEveryRequirementCellIsServedOrNamesAClosedReason(t *testing.T) {
	capabilities := liveCapabilityList(t)
	seed := contextfabric.GenerateObligationSeed(capabilities)

	validReasons := map[contextfabric.RequirementUnavailableReason]bool{}
	for _, reason := range contextfabric.RequirementUnavailableReasonVocabulary() {
		validReasons[reason] = true
	}

	cells := 0
	framesWithRows := 0
	for _, testCase := range traceFrames() {
		rows := contextfabric.DeriveRequirements(testCase.frame, seed, capabilities)
		if len(rows) == 0 {
			t.Errorf("%s (%s): derived no requirement rows at all", testCase.id, testCase.shape)
			continue
		}
		framesWithRows++
		if err := contextfabric.RequirementRowsAreWellFormed(rows); err != nil {
			t.Errorf("%s (%s): %v", testCase.id, testCase.shape, err)
		}
		for _, row := range rows {
			if row.Served() {
				switch row.Kind {
				case contextfabric.ObligationKindComputed:
					if row.Step == "" {
						t.Errorf("%s: computed %s@%s names no server step", testCase.id, row.Obligation, row.Subject)
					}
				default:
					if len(row.FactKinds) == 0 {
						t.Errorf("%s: served read %s@%s names no fact kind", testCase.id, row.Obligation, row.Subject)
					}
				}
			} else if !validReasons[row.Unavailable] {
				t.Errorf("%s: %s@%s is unavailable for out-of-vocabulary reason %q", testCase.id, row.Obligation, row.Subject, row.Unavailable)
			}
			cells++
		}
	}
	if framesWithRows != len(traceFrames()) {
		t.Errorf("%d of %d frames produced rows", framesWithRows, len(traceFrames()))
	}
	if cells == 0 {
		t.Fatal("no requirement cells reached the assertions -- the gate proved nothing")
	}
	t.Logf("O9: %d requirement cells derived across %d frames, all served or named", cells, framesWithRows)
}

// TestEveryComputedObligationNamesItsServerStep is O9's second clause,
// asserted over the live corpus rather than over the fixture.
//
// The frozen table modelled `ranking` as a READ with a required table shape
// no producer declares, so BAR question Q2's DEFINING obligation was
// unavailable by construction (round 4, N3). That mis-typing is what this
// clause exists to keep out.
func TestEveryComputedObligationNamesItsServerStep(t *testing.T) {
	capabilities := liveCapabilityList(t)
	seed := contextfabric.GenerateObligationSeed(capabilities)

	computed, servedComputed, unavailableComputed := 0, 0, 0
	for _, testCase := range traceFrames() {
		for _, row := range contextfabric.DeriveRequirements(testCase.frame, seed, capabilities) {
			if row.Kind != contextfabric.ObligationKindComputed {
				continue
			}
			computed++
			want, named := contextfabric.StepForComputedObligation(row.Obligation)
			if !named {
				t.Errorf("%s: %s is classified computed but names no step in the vocabulary", testCase.id, row.Obligation)
				continue
			}
			// A COMPUTED CELL EITHER NAMES ITS STEP OR NAMES A CLOSED REASON
			// IT CANNOT RUN -- exactly the disjunction the READ clause above
			// has always had, and never a silent third state.
			//
			// The clause used to demand a step unconditionally. An
			// adversarial round showed that is too strong: an
			// organization-scope frame names a member kind, so the coordinate
			// is legitimate, but nothing discovers that population -- the
			// step has no input and the cell cannot be served. Demanding a
			// step there forced the row to CLAIM a server for work nothing
			// could do, which is the same over-claim the execution
			// declaration was added to stop, one level in. Naming the reason
			// is strictly more than naming an unrunnable step.
			if !row.Served() {
				if row.Unavailable == "" {
					t.Errorf("%s: computed %s@%s is unserved and names no reason -- the silent emptiness this gate exists to forbid",
						testCase.id, row.Obligation, row.Subject)
				}
				if row.Step != "" {
					t.Errorf("%s: computed %s@%s names BOTH a step and a reason it cannot run -- two answers to what became of the cell",
						testCase.id, row.Obligation, row.Subject)
				}
				unavailableComputed++
				continue
			}
			if row.Step != want {
				t.Errorf("%s: %s@%s names step %q, want %q", testCase.id, row.Obligation, row.Subject, row.Step, want)
			}
			servedComputed++
		}
	}
	if computed == 0 {
		t.Fatal("no computed obligation reached the assertions; Q2, C4, C5 and C7 all derive one, so the corpus or the derivation is wrong")
	}
	// BOTH sides of the disjunction must be populated, or the clause is
	// one-sided: all-served would make the unavailable arm dead, and
	// all-unavailable would mean no frame in the corpus can run a
	// computation at all.
	if servedComputed == 0 || unavailableComputed == 0 {
		t.Fatalf("computed cells are one-sided: %d served, %d unavailable -- one arm of this clause is untested",
			servedComputed, unavailableComputed)
	}
	t.Logf("O9: %d computed requirement cells -- %d name their server step, %d name a closed reason they cannot run",
		computed, servedComputed, unavailableComputed)
}

// TestStateCompositionParityAgainstTheLiveRegistry is the N2 parity
// property: the generated seed's `state` set for team and project equals
// the CHAOS-4347 status composition, by SET EQUALITY IN BOTH DIRECTIONS.
//
// Both directions matter and one direction would have missed the defect
// that produced the shipped declaration shape: a flat obligation list
// diverged only by an EXTRA kind, never a missing one, so a subset check
// would have passed while the plan read facts the composition excludes.
func TestStateCompositionParityAgainstTheLiveRegistry(t *testing.T) {
	capabilities := liveCapabilityList(t)
	seed := contextfabric.GenerateObligationSeed(capabilities)
	composition := contextfabric.StatusCategoryCompositionForTest()

	checked := 0
	for _, subject := range []contextfabric.SubjectKind{contextfabric.SubjectTeam, contextfabric.SubjectProject} {
		want, declared := composition[subject]
		if !declared || len(want) == 0 {
			t.Fatalf("the composition has no row for %q, so this comparison has no reference", subject)
		}
		got := seed.KindsFor(contextfabric.ObligationState, subject)
		if diff := setDifference(got, want); len(diff) > 0 {
			t.Errorf("state@%s: the seed serves %v, which the composition excludes", subject, diff)
		}
		if diff := setDifference(want, got); len(diff) > 0 {
			t.Errorf("state@%s: the composition names %v, which the seed does not serve", subject, diff)
		}
		checked++
	}
	if checked != 2 {
		t.Fatalf("compared %d composition rows, want 2", checked)
	}
}

func setDifference(from, minus []contextfabric.FactKind) []contextfabric.FactKind {
	remove := make(map[contextfabric.FactKind]bool, len(minus))
	for _, kind := range minus {
		remove[kind] = true
	}
	var diff []contextfabric.FactKind
	for _, kind := range from {
		if !remove[kind] {
			diff = append(diff, kind)
		}
	}
	sort.Slice(diff, func(i, j int) bool { return diff[i] < diff[j] })
	return diff
}

// TestRequirementTraceArtifactIsRegenerated is the ROT GUARD -- the one the
// derivation gets, per the slice's own bar.
//
// The artifact is an OUTPUT. It is produced by calling the production
// renderers over the live registry and compared byte for byte with the
// checked-in file. There is no second table it is rendered from and no
// constant in this file it is compared against, which is the property the
// declaration slice's artifact lacked through two review rounds: there, the
// renderer walked a hand table, so deleting a cell removed it from the
// artifact AND from the assertion and everything stayed green.
//
// THE MEASUREMENT LIVES IN THE ARTIFACT, NOT IN GO SOURCE. The derived and
// unserved cell counts and the cause distribution are lines of the
// generated file. A registry change moves them and the diff is the review
// surface; there is deliberately no constant here to edit into agreement.
// A count that moves is a MEASUREMENT to be explained -- and the causes at
// the foot are what explain it, since the total can stay put while its
// composition changes (a producer gaining a subject kind while another
// loses one nets to zero).
func TestRequirementTraceArtifactIsRegenerated(t *testing.T) {
	generated := renderRequirementTrace(t)

	recorded, err := os.ReadFile(requirementTraceArtifact)
	if err != nil {
		t.Fatalf("reading %s: %v\n\nthe generated content is:\n\n%s", requirementTraceArtifact, err, generated)
	}
	if string(recorded) != generated {
		t.Fatalf("%s is stale. Regenerate it and read the cause distribution at the foot: "+
			"the total can stay put while its composition moves, so the causes are what say what changed.\n\n--- generated ---\n%s", requirementTraceArtifact, generated)
	}
}

// renderRequirementTrace produces the artifact's whole content from the
// production functions and the live registry.
func renderRequirementTrace(t *testing.T) string {
	t.Helper()
	capabilities := liveCapabilityList(t)
	seed := contextfabric.GenerateObligationSeed(capabilities)

	var out strings.Builder
	out.WriteString("# GENERATED by TestRequirementTraceArtifactIsRegenerated from the PRODUCTION\n")
	out.WriteString("# derivation (DeriveRequirementCoordinates + DeriveRequirements) run against\n")
	out.WriteString("# the live fact registry. DO NOT EDIT BY HAND: the test regenerates this file\n")
	out.WriteString("# and fails on any difference.\n")
	out.WriteString("#\n")
	out.WriteString("# Oracle O9, design 13.11a. Thirteen frames: the acceptance questions Q1, Q1',\n")
	out.WriteString("# Q2, Q-A and Q-B, the composed cases C1-C7, and B5. QUESTION IDS ONLY -- no\n")
	out.WriteString("# corpus text appears here or in the code that renders it.\n")
	out.WriteString("#\n")
	out.WriteString("# Columns: obligation / role / subject kind / completion scope / quantifier /\n")
	out.WriteString("# server. A server reads `UNAVAILABLE <reason>` where no producer can serve the\n")
	out.WriteString("# cell -- never a silent blank, which is the condition O9 asserts.\n")
	out.WriteString("#\n")
	out.WriteString("# THE ANCHOR ROLE HAS NO ROW ANYWHERE, by design. ScopedSetExpression's\n")
	out.WriteString("# AnchorTerms are retrieval pointers, never values, so an anchor's subject kind\n")
	out.WriteString("# is settled at resolution time and the frame -- immutable before resolution --\n")
	out.WriteString("# cannot name it. The absence is a measured bound, not an omission.\n")

	var all, recorded []contextfabric.DerivedRequirement
	for _, testCase := range traceFrames() {
		rows := contextfabric.DeriveRequirements(testCase.frame, seed, capabilities)
		all = append(all, rows...)
		if testCase.recorded {
			recorded = append(recorded, rows...)
		}
		marker := ""
		if !testCase.recorded {
			marker = "  (ADDED to the recorded thirteen)"
		}
		out.WriteString("\n")
		out.WriteString(contextfabric.RenderRequirements(testCase.id+"  ["+testCase.shape+"]"+marker, rows))
	}

	out.WriteString("\n")
	writeMeasurement(&out, "MEASUREMENT (recorded thirteen frames)", recorded, recordedFrameCount())
	writeMeasurement(&out, "MEASUREMENT (whole corpus)", all, len(traceFrames()))
	out.WriteString("#\n")
	out.WriteString(contextfabric.RenderRequirementCauseDistribution(contextfabric.RequirementCauseDistribution(all)))
	return out.String()
}

// writeMeasurement reports one cell tally.
//
// THE RECORDED-THIRTEEN SUBTOTAL IS REPORTED SEPARATELY so that this gate's
// number stays directly comparable to the measurement on record, which was
// taken over those thirteen frames. Folding the added frame into a single
// total would move the number for a reason that has nothing to do with the
// derivation, and an unattributable movement is exactly what a measurement
// must not have.
func writeMeasurement(out *strings.Builder, label string, rows []contextfabric.DerivedRequirement, frames int) {
	served, unserved := 0, 0
	for _, row := range rows {
		if row.Served() {
			served++
		} else {
			unserved++
		}
	}
	fmt.Fprintf(out, "# %s: %d requirement cells derived over %d frames; %d served, %d unserved.\n",
		label, len(rows), frames, served, unserved)
}

// TestTheCorpusExercisesEveryVariantAndEveryRole is the gate's own
// non-vacuity check.
//
// A corpus that never builds a grouped frame cannot notice a broken group
// rule, and a corpus with no scoped operand is exactly the blind spot round
// 3 found. Rather than trusting the thirteen frames to be diverse, the
// coverage is asserted: every member of the subject-expression vocabulary
// and every subject role must appear.
func TestTheCorpusExercisesEveryVariantAndEveryRole(t *testing.T) {
	variants := map[contextfabric.SubjectExpressionKind]bool{}
	roles := map[contextfabric.SubjectRole]bool{}
	for _, testCase := range traceFrames() {
		variants[testCase.frame.SubjectExpression.Kind] = true
		for _, coordinate := range contextfabric.DeriveRequirementCoordinates(testCase.frame) {
			roles[coordinate.Role] = true
		}
	}
	for _, variant := range contextfabric.SubjectExpressionKindVocabulary() {
		if !variants[variant] {
			t.Errorf("no frame in the corpus uses subject expression %q, so the gate cannot see that variant's role rules", variant)
		}
	}
	for _, role := range contextfabric.SubjectRoleVocabulary() {
		if !roles[role] {
			t.Errorf("no frame in the corpus produces role %q, so the gate cannot see its completion scope or its attachment rule", role)
		}
	}
}
