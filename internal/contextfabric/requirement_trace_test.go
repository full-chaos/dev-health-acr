// ORACLE O9 -- the S7b-ii entry gate, rebuilt on the PRODUCTION derivation.
// Design §13.11a (O9), §13.15.1 (the executed trace that forced the
// excision), §13.15.2 (the per-rule evidence obligations), law L10.
//
// WHAT CHANGED SINCE THE DECLARATION SLICE, AND WHY IT MATTERS. That slice
// carried a hand-written coordinate table inside a test file and shipped a
// PINNED empty-cell count. Three adversarial rounds each found a hole in
// the code written to close the previous round's finding, and the
// scaffolding was removed rather than approximated a fourth time. The root
// cause was structural: the coordinates, the artifact that displayed them
// and the assertion that checked them were three views of ONE table living
// in ONE file, so a coordinated edit moved all three and every test stayed
// green.
//
// Here there is no table. The coordinates come from
// contextfabric.DeriveRequirementCoordinates and the rows from
// contextfabric.DeriveRequirements -- PRODUCTION functions -- run against
// devhealthfacts.NewProviders, the live registry. The artifact is their
// OUTPUT: it is regenerated by calling them and diffed, so there is nothing
// for an edit to be coordinated across. The unserved/derived pair is a
// number IN THE ARTIFACT, not a constant in this file, which is what makes
// it a measurement rather than something a reviewer can tune to match.
//
// WHAT O9 ASSERTS, in the ticket's own words: "every required READ
// obligation cell either names >=1 fact kind a producer can serve for that
// subject kind, or names `unavailable` with a closed reason token -- never
// silently empty; every COMPUTED obligation names its server step
// (RankCohort for ranking, a cardinality for count); and `state`@team and
// `state`@project equal statusCategoryFactKindComposition by set equality
// in both directions". All three are asserted below. Note what that
// condition IS and IS NOT: it is not "every cell is served" -- the registry
// genuinely cannot serve some of them, and pretending otherwise is what the
// frozen seed did. It is that no cell is silently empty. The count of cells
// the registry cannot serve is REPORTED, with its causes, in the artifact.
//
// IT LIVES IN THE EXTERNAL TEST PACKAGE because devhealthfacts imports
// contextfabric, so an in-package file cannot import it back. Running
// against a hand-built fixture registry instead would test the fixture, not
// the registry the engine actually plans against -- and that is the whole
// point of the gate. (Rule-level tests against a constructed registry do
// exist, in requirement_derivation_test.go, for the opposite reason: those
// pin rules that must NOT move when a declaration does.)
//
// CORPUS SAFETY. Frames are identified by QUESTION ID and by a STRUCTURAL
// label (topology + operation) only. No corpus question text appears in
// this file, in its output, or in the artifact. The frames are built
// THROUGH the shipped frame layer (DeriveFrameObligations), never by
// hand-typing an obligation list, so a change to §13.2.3's tables moves
// this trace with it rather than leaving it silently disagreeing.
//
// HOST-ONLY. The registry reader this file uses (liveCapabilityList, in
// obligation_seed_test.go) reads Capability() declarations and never
// constructs a provider client, so nothing here starts a container. The
// devhealthfacts PACKAGE's own tests do start ClickHouse; they are not run
// by this file's command.

